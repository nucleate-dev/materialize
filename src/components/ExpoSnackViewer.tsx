"use client";

import {
  forwardRef,
  useCallback,
  useEffect,
  useImperativeHandle,
  useRef,
  useState,
} from "react";
import type { SnackListenerSubscription, SnackState } from "snack-sdk";
import { Snack } from "snack-sdk";
import { DEFAULT_DEPENDENCIES } from "../templates/defaultApp";
import { Database } from "@/lib/types/database.types";

interface SnackWithSubscriptions extends Snack {
  _subscriptions?: SnackListenerSubscription[];
}

interface ExpoSnackViewerProps {
  files: Record<string, Database["public"]["Tables"]["prototype_files"]["Row"]>;
  onResetToDefault?: () => void;
  hideControls?: boolean;
}

export interface ExpoSnackViewerRef {
  forceRefresh: () => void;
}

type PreviewMode = "web" | "mobile";

const ExpoSnackViewer = forwardRef<ExpoSnackViewerRef, ExpoSnackViewerProps>(
  ({ files, onResetToDefault, hideControls = false }, ref) => {
    const [snack, setSnack] = useState<SnackWithSubscriptions | null>(null);
    const [snackState, setSnackState] = useState<SnackState | null>(null);
    const [isLoading, setIsLoading] = useState(true);
    const [error, setError] = useState<string | null>(null);
    const [previewMode, setPreviewMode] = useState<PreviewMode>("mobile");
    const [refreshKey, setRefreshKey] = useState(0);
    const [mobileSize, setMobileSize] = useState({ width: 300, height: 600 });

    // Ref for the iframe's contentWindow
    const webPreviewRef = useRef<Window | null>(null);

    // Force refresh method
    const forceRefresh = useCallback(() => {
      if (snack && snackState?.webPreviewURL) {
        // Method 1: Try iframe refresh
        const iframe = document.querySelector(
          'iframe[title="React Native Preview"], iframe[title="React Native Web Preview"]',
        ) as HTMLIFrameElement;
        if (iframe) {
          const currentSrc = iframe.src;
          iframe.src = "about:blank";
          setTimeout(() => {
            iframe.src = currentSrc;
          }, 100);
        }

        // Method 2: Update refresh key to force React re-render
        setRefreshKey((prev) => prev + 1);
      }
    }, [snack, snackState?.webPreviewURL]);

    // Expose forceRefresh method to parent
    useImperativeHandle(
      ref,
      () => ({
        forceRefresh,
      }),
      [forceRefresh],
    );

    useEffect(() => {
      let snackSDK: SnackWithSubscriptions | null = null;

      const initializeSnack = () => {
        try {
          setIsLoading(true);
          setError(null);

          const initialFiles = Object.entries(files).reduce(
            (acc, [fileName, file]) => {
              acc[fileName] = {
                type: "CODE" as const,
                contents: file.contents,
              };
              return acc;
            },
            {} as Record<string, { type: "CODE"; contents: string }>,
          );

          snackSDK = new Snack({
            files: initialFiles,
            dependencies: DEFAULT_DEPENDENCIES,
            online: true,
            name: "React Native Chat Assistant",
            description: "Generated by AI assistant",
            webPreviewRef: webPreviewRef,
          });

          const stateSubscription = snackSDK.addStateListener((state) => {
            setSnackState(state);
          });

          const logSubscription = snackSDK.addLogListener((log) => {
            console.log("Snack log:", log);
          });

          setSnack(snackSDK);
          setSnackState(snackSDK.getState());
          setIsLoading(false);

          (snackSDK as SnackWithSubscriptions)._subscriptions = [
            stateSubscription,
            logSubscription,
          ];
        } catch (err) {
          console.error("Failed to initialize Snack:", err);
          setError(
            err instanceof Error ? err.message : "Failed to initialize Snack",
          );
          setIsLoading(false);
        }
      };

      initializeSnack();

      return () => {
        if (snackSDK && snackSDK._subscriptions) {
          snackSDK._subscriptions.forEach((unsubscribe) => {
            if (unsubscribe) {
              unsubscribe();
            }
          });
        }
      };
    }, []); // This effect should run only once on mount

    useEffect(() => {
      const updateSnackFiles = async () => {
        if (!snack) return;

        try {
          setError(null);
          const snackFiles = Object.entries(files).reduce(
            (acc, [fileName, file]) => {
              acc[fileName] = {
                type: "CODE" as const,
                contents: file.contents,
              };
              return acc;
            },
            {} as Record<string, { type: "CODE"; contents: string }>,
          );
          snack.updateFiles(snackFiles);
        } catch (err) {
          console.error("Failed to update Snack files:", err);
          setError(
            err instanceof Error ? err.message : "Failed to update code",
          );
        }
      };

      if (files) {
        updateSnackFiles();
      }
    }, [files, snack, forceRefresh]);

    const snackUrl = snackState?.url;
    const webPreviewURL = snackState?.webPreviewURL;

    const handleRefresh = () => {
      if (webPreviewRef.current && webPreviewURL) {
        webPreviewRef.current.location = webPreviewURL;
      }
    };

    const handleModeChange = (mode: PreviewMode) => {
      setPreviewMode(mode);
    };

    const handleMouseDown = (e: React.MouseEvent) => {
      e.preventDefault();
      e.stopPropagation();

      const startX = e.clientX;
      const startY = e.clientY;
      const startWidth = mobileSize.width;
      const startHeight = mobileSize.height;

      const handleMouseMove = (moveEvent: MouseEvent) => {
        const deltaX = moveEvent.clientX - startX;
        const deltaY = moveEvent.clientY - startY;

        const newWidth = Math.max(250, Math.min(500, startWidth + deltaX));
        const newHeight = Math.max(400, Math.min(800, startHeight + deltaY));

        setMobileSize({ width: newWidth, height: newHeight });
      };

      const handleMouseUp = () => {
        document.removeEventListener("mousemove", handleMouseMove);
        document.removeEventListener("mouseup", handleMouseUp);
        document.body.style.cursor = "";
        document.body.style.userSelect = "";
      };

      document.addEventListener("mousemove", handleMouseMove);
      document.addEventListener("mouseup", handleMouseUp);
      document.body.style.cursor = "se-resize";
      document.body.style.userSelect = "none";
    };

    return (
      <div className="flex flex-col h-full bg-transparent">
        {/* Compact Header with Controls */}
        <div className="flex items-center justify-between p-3 bg-white/40 dark:bg-boxdark/40 border-b border-white/20 dark:border-strokedark/30">
          <div className="flex items-center space-x-3">
            {/* Mode Selector */}
            <div className="flex bg-white/60 dark:bg-boxdark/60 rounded-lg p-1 backdrop-blur-sm">
              <button
                onClick={() => handleModeChange("mobile")}
                className={`px-3 py-1.5 text-sm rounded-md transition-all duration-300 font-medium ${
                  previewMode === "mobile"
                    ? "bg-gradient-to-r from-meta-3 to-meta-5 text-white shadow-sm transform scale-105"
                    : "text-body dark:text-bodydark hover:text-black dark:hover:text-white"
                }`}
              >
                Mobile
              </button>
              <button
                onClick={() => handleModeChange("web")}
                className={`px-3 py-1.5 text-sm rounded-md transition-all duration-300 font-medium ${
                  previewMode === "web"
                    ? "bg-gradient-to-r from-meta-3 to-meta-5 text-white shadow-sm transform scale-105"
                    : "text-body dark:text-bodydark hover:text-black dark:hover:text-white"
                }`}
              >
                Web
              </button>
            </div>
          </div>

          {!hideControls && (
            <div className="flex items-center space-x-2">
              <button
                onClick={onResetToDefault}
                className="bg-gradient-to-r from-meta-1 to-meta-6 text-white px-3 py-1.5 rounded-lg text-sm font-medium hover:shadow-lg transition-all duration-300 disabled:opacity-50"
                disabled={isLoading}
                title="Reset to default app"
              >
                Reset
              </button>
              <button
                onClick={handleRefresh}
                className="bg-gradient-to-r from-meta-3 to-meta-5 text-white px-3 py-1.5 rounded-lg text-sm font-medium hover:shadow-lg transition-all duration-300 disabled:opacity-50"
                disabled={isLoading || !webPreviewURL}
              >
                Refresh
              </button>
            </div>
          )}
        </div>

        {/* Status */}
        {(isLoading || error) && (
          <div className="p-3 bg-white/20 dark:bg-boxdark/20 border-b border-white/20 dark:border-strokedark/30">
            {isLoading && (
              <div className="flex items-center space-x-2 text-primary">
                <div className="w-4 h-4 border-2 border-primary border-t-transparent rounded-full animate-spin"></div>
                <span className="text-sm font-medium">Loading preview...</span>
              </div>
            )}

            {error && (
              <div className="flex items-center space-x-2 text-meta-1">
                <svg
                  className="w-4 h-4"
                  fill="currentColor"
                  viewBox="0 0 20 20"
                >
                  <path
                    fillRule="evenodd"
                    d="M18 10a8 8 0 11-16 0 8 8 0 0116 0zm-7 4a1 1 0 11-2 0 1 1 0 012 0zm-1-9a1 1 0 00-1 1v4a1 1 0 102 0V6a1 1 0 00-1-1z"
                    clipRule="evenodd"
                  />
                </svg>
                <span className="text-sm font-medium">{error}</span>
              </div>
            )}
          </div>
        )}

        {/* Preview */}
        <div className="flex-1 relative flex items-center justify-center bg-gradient-to-br from-gray-50/50 to-gray-100/50 dark:from-boxdark/20 dark:to-meta-4/20 p-4">
          {isLoading && !webPreviewURL ? (
            <div className="flex items-center justify-center h-full">
              <div className="text-center">
                <div className="w-8 h-8 border-4 border-blue-600 border-t-transparent rounded-full animate-spin mx-auto mb-4"></div>
                <p className="text-gray-600">
                  Setting up your React Native preview...
                </p>
              </div>
            </div>
          ) : previewMode === "mobile" ? (
            /* --- START: iPhone 15 Pro device frame --- */
            <div
              id="mobile-frame"
              className="relative mx-auto select-none"
              style={{
                width: mobileSize.width + 16,
                height: mobileSize.height + 16,
              }}
            >
              {/* iPhone 15 Pro frame with titanium-like appearance */}
              <div
                className="relative bg-gradient-to-br from-gray-700 via-gray-800 to-gray-900 shadow-2xl"
                style={{
                  width: mobileSize.width + 16,
                  height: mobileSize.height + 16,
                  borderRadius: "2.5rem",
                  border: "1px solid #1f2937",
                  boxShadow:
                    "0 25px 50px -12px rgba(0, 0, 0, 0.5), inset 0 1px 0 rgba(255, 255, 255, 0.1)",
                }}
              >
                {/* Dynamic Island */}
                <div
                  className="absolute bg-black rounded-full"
                  style={{
                    width: mobileSize.width * 0.4,
                    height: "24px",
                    top: "6px",
                    left: "50%",
                    transform: "translateX(-50%)",
                    borderRadius: "12px",
                  }}
                ></div>

                {/* Volume buttons */}
                <div className="absolute -left-[3px] top-[80px] w-[2px] h-[32px] bg-gray-600 rounded-l-lg"></div>
                <div className="absolute -left-[3px] top-[120px] w-[2px] h-[32px] bg-gray-600 rounded-l-lg"></div>
                <div className="absolute -left-[3px] top-[160px] w-[2px] h-[48px] bg-gray-600 rounded-l-lg"></div>

                {/* Power button */}
                <div className="absolute -right-[3px] top-[140px] w-[2px] h-[48px] bg-gray-600 rounded-r-lg"></div>

                {/* Screen area */}
                <div
                  className="absolute bg-black overflow-hidden"
                  style={{
                    width: mobileSize.width,
                    height: mobileSize.height,
                    top: "8px",
                    left: "8px",
                    borderRadius: "2.2rem",
                    boxShadow: "inset 0 0 0 1px rgba(255, 255, 255, 0.1)",
                  }}
                >
                  <iframe
                    key={`mobile-${refreshKey}`}
                    ref={(c) =>
                      (webPreviewRef.current = c?.contentWindow ?? null)
                    }
                    className="w-full h-full"
                    title="React Native Preview"
                    src={webPreviewURL}
                    sandbox="allow-scripts allow-same-origin allow-forms allow-downloads allow-modals allow-popups allow-presentation"
                  />
                </div>

                {/* Resize handle */}
                <div
                  className="absolute bottom-1 right-1 w-4 h-4 cursor-se-resize opacity-60 hover:opacity-100 transition-opacity"
                  onMouseDown={handleMouseDown}
                >
                  <div className="w-full h-full bg-gray-400 rounded-sm flex items-center justify-center">
                    <svg
                      width="8"
                      height="8"
                      viewBox="0 0 8 8"
                      fill="currentColor"
                    >
                      <path d="M8 0v2L6 0h2zM8 4v2L6 4h2zM8 8v0L6 6h2zM4 8v0L2 6h2z" />
                    </svg>
                  </div>
                </div>
              </div>
            </div>
          ) : (
            /* --- END: Mobile device frame --- */
            /* --- START: Web preview --- */
            <div className="w-full h-full max-w-4xl mx-auto">
              <div className="bg-white rounded-lg shadow-lg overflow-hidden h-full">
                <div className="bg-gray-100 px-4 py-2 border-b flex items-center space-x-2">
                  <div className="flex space-x-1">
                    <div className="w-3 h-3 bg-red-500 rounded-full"></div>
                    <div className="w-3 h-3 bg-yellow-500 rounded-full"></div>
                    <div className="w-3 h-3 bg-green-500 rounded-full"></div>
                  </div>
                  <span className="text-sm text-gray-600 ml-2">
                    Web Preview
                  </span>
                </div>
                <iframe
                  key={`web-${refreshKey}`}
                  ref={(c) =>
                    (webPreviewRef.current = c?.contentWindow ?? null)
                  }
                  className="w-full h-full min-h-[500px]"
                  title="React Native Web Preview"
                  src={webPreviewURL}
                  sandbox="allow-scripts allow-same-origin allow-forms allow-downloads allow-modals allow-popups allow-presentation"
                />
              </div>
            </div>
            /* --- END: Web preview --- */
          )}
        </div>

        {/* File Info */}
        {!hideControls && (
          <div className="border-t p-3 bg-white">
            <div className="text-xs text-gray-500">
              Files: {Object.keys(files).join(", ")}
              {snackUrl && (
                <span className="ml-2">• Connected to Expo Snack</span>
              )}
            </div>
          </div>
        )}
      </div>
    );
  },
);

ExpoSnackViewer.displayName = "ExpoSnackViewer";

export default ExpoSnackViewer;
