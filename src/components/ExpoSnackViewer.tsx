'use client';

import { useEffect, useRef, useState } from 'react';
import type { SnackListenerSubscription, SnackState } from 'snack-sdk';
import { Snack } from 'snack-sdk';
import { DEFAULT_DEPENDENCIES, getDefaultSnackFiles } from '../templates/defaultApp';
import { SnackFiles } from '../types/chat';

interface SnackWithSubscriptions extends Snack {
  _subscriptions?: SnackListenerSubscription[];
}

interface ExpoSnackViewerProps {
  files: SnackFiles;
  onFilesChange?: (files: SnackFiles) => void;
}

export default function ExpoSnackViewer({ files, onFilesChange }: ExpoSnackViewerProps) {
  const [snack, setSnack] = useState<SnackWithSubscriptions | null>(null);
  const [snackState, setSnackState] = useState<SnackState | null>(null);
  const [isLoading, setIsLoading] = useState(true);
  const [error, setError] = useState<string | null>(null);

  // Ref for the iframe's contentWindow
  const webPreviewRef = useRef<Window | null>(null);

  useEffect(() => {
    let snackSDK: SnackWithSubscriptions | null = null;

    const initializeSnack = () => {
      try {
        setIsLoading(true);
        setError(null);

        const initialFiles = Object.keys(files).length > 0 ? files : getDefaultSnackFiles();

        snackSDK = new Snack({
          files: initialFiles,
          dependencies: DEFAULT_DEPENDENCIES,
          online: true,
          name: 'React Native Chat Assistant',
          description: 'Generated by AI assistant',
          webPreviewRef: webPreviewRef,
        });

        const stateSubscription = snackSDK.addStateListener((state) => {
          setSnackState(state);
        });

        const logSubscription = snackSDK.addLogListener((log) => {
          console.log('Snack log:', log);
        });

        setSnack(snackSDK);
        setSnackState(snackSDK.getState());
        setIsLoading(false);

        (snackSDK as SnackWithSubscriptions)._subscriptions = [stateSubscription, logSubscription];
      } catch (err) {
        console.error('Failed to initialize Snack:', err);
        setError(err instanceof Error ? err.message : 'Failed to initialize Snack');
        setIsLoading(false);
      }
    };

    initializeSnack();

    return () => {
      if (snackSDK && snackSDK._subscriptions) {
        snackSDK._subscriptions.forEach((unsubscribe) => {
          if (unsubscribe) {
            unsubscribe();
          }
        });
      }
    };
  }, []); // This effect should run only once on mount

  useEffect(() => {
    const updateSnackFiles = async () => {
      if (!snack) return;

      try {
        setError(null);
        await snack.updateFiles(files);
      } catch (err) {
        console.error('Failed to update Snack files:', err);
        setError(err instanceof Error ? err.message : 'Failed to update code');
      }
    };

    if (files) {
      updateSnackFiles();
    }
  }, [files, snack]);

  const snackUrl = snackState?.url;
  const webPreviewURL = snackState?.webPreviewURL;

  const handleRefresh = () => {
    if (webPreviewRef.current && webPreviewURL) {
      webPreviewRef.current.location = webPreviewURL;
    }
  };

  const handleReset = () => {
    const defaultFiles = getDefaultSnackFiles();
    if (onFilesChange) {
      onFilesChange(defaultFiles);
    }
  };

  return (
    <div className="flex flex-col h-full bg-gray-50">
      {/* Header */}
      <div className="border-b p-4 bg-white">
        <div className="flex items-center justify-between">
          <div>
            <h2 className="text-lg font-semibold text-gray-900">Live Preview</h2>
            <p className="text-sm text-gray-600">Powered by Expo Snack</p>
          </div>
          <div className="flex space-x-2">
            <button
              onClick={handleRefresh}
              className="bg-blue-600 text-white px-3 py-1 rounded text-sm hover:bg-blue-700 transition-colors"
              disabled={isLoading || !webPreviewURL}
            >
              Refresh
            </button>
            <button
              onClick={handleReset}
              className="bg-gray-600 text-white px-3 py-1 rounded text-sm hover:bg-gray-700 transition-colors"
              disabled={isLoading}
            >
              Reset
            </button>
          </div>
        </div>

        {snackUrl && (
          <div className="mt-2">
            <button
              onClick={() => {
                navigator.clipboard.writeText(snackUrl);
              }}
              className="text-blue-600 hover:text-blue-800 text-sm flex items-center space-x-1"
            >
              <svg className="w-4 h-4" fill="none" stroke="currentColor" viewBox="0 0 24 24">
                <path strokeLinecap="round" strokeLinejoin="round" strokeWidth={2} d="M8 16H6a2 2 0 01-2-2V6a2 2 0 012-2h8a2 2 0 012 2v2m-6 12h8a2 2 0 002-2v-8a2 2 0 00-2-2h-8a2 2 0 00-2 2v8a2 2 0 002 2z" />
              </svg>
              <span>Copy link</span>
            </button>
          </div>
        )}
      </div>

      {/* Status */}
      {(isLoading || error) && (
        <div className="p-4 bg-white border-b">
          {isLoading && (
            <div className="flex items-center space-x-2 text-blue-600">
              <div className="w-4 h-4 border-2 border-blue-600 border-t-transparent rounded-full animate-spin"></div>
              <span className="text-sm">Loading preview...</span>
            </div>
          )}

          {error && (
            <div className="flex items-center space-x-2 text-red-600">
              <svg className="w-4 h-4" fill="currentColor" viewBox="0 0 20 20">
                <path fillRule="evenodd" d="M18 10a8 8 0 11-16 0 8 8 0 0116 0zm-7 4a1 1 0 11-2 0 1 1 0 012 0zm-1-9a1 1 0 00-1 1v4a1 1 0 102 0V6a1 1 0 00-1-1z" clipRule="evenodd" />
              </svg>
              <span className="text-sm">{error}</span>
            </div>
          )}
        </div>
      )}

      {/* Preview */}
      <div className="flex-1 relative flex items-center justify-center bg-gray-200 p-4">
        {isLoading && !webPreviewURL ? (
          <div className="flex items-center justify-center h-full">
            <div className="text-center">
              <div className="w-8 h-8 border-4 border-blue-600 border-t-transparent rounded-full animate-spin mx-auto mb-4"></div>
              <p className="text-gray-600">Setting up your React Native preview...</p>
            </div>
          </div>
        ) : (
          /* --- START: Mobile device frame --- */
          <div className="relative mx-auto border-gray-800 bg-gray-800 border-[10px] rounded-[2.5rem] h-[600px] w-[300px] shadow-xl">
            <div className="w-[140px] h-[18px] bg-gray-800 top-0 rounded-b-[1rem] left-1/2 -translate-x-1/2 absolute"></div>
            <div className="h-[46px] w-[3px] bg-gray-800 absolute -left-[13px] top-[62px] rounded-l-lg"></div>
            <div className="h-[46px] w-[3px] bg-gray-800 absolute -left-[13px] top-[114px] rounded-l-lg"></div>
            <div className="h-[64px] w-[3px] bg-gray-800 absolute -right-[13px] top-[132px] rounded-r-lg"></div>
            <div className="rounded-[2rem] overflow-hidden w-full h-full bg-white">
              <iframe
                ref={(c) => (webPreviewRef.current = c?.contentWindow ?? null)}
                className="w-full h-full"
                title="React Native Preview"
                src={webPreviewURL}
                sandbox="allow-scripts allow-same-origin allow-forms allow-downloads allow-modals allow-popups allow-presentation"
              />
            </div>
          </div>
          /* --- END: Mobile device frame --- */
        )}
      </div>

      {/* File Info */}
      <div className="border-t p-3 bg-white">
        <div className="text-xs text-gray-500">
          Files: {Object.keys(files).join(', ') || 'App.js'}
          {snackUrl && <span className="ml-2">• Connected to Expo Snack</span>}
        </div>
      </div>
    </div>
  );
}