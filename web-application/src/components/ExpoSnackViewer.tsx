"use client";

import { Badge } from "@/components/ui/badge";
import { Button } from "@/components/ui/button";
import {
  Dialog,
  DialogContent,
  DialogFooter,
  DialogHeader,
  DialogTitle,
} from "@/components/ui/dialog";
import {
  DropdownMenu,
  DropdownMenuContent,
  DropdownMenuItem,
  DropdownMenuSeparator,
  DropdownMenuTrigger,
} from "@/components/ui/dropdown-menu";
import { Input } from "@/components/ui/input";
import { Label } from "@/components/ui/label";
import { Database } from "@/lib/types/database.types";
import {
  Monitor,
  RefreshCw,
  RotateCcw,
  Settings,
  Smartphone,
} from "lucide-react";
import {
  forwardRef,
  useCallback,
  useEffect,
  useImperativeHandle,
  useRef,
  useState,
} from "react";
import type { SnackListenerSubscription, SnackState } from "snack-sdk";
import { Snack } from "snack-sdk";
import { DEFAULT_DEPENDENCIES } from "../templates/defaultApp";

interface SnackWithSubscriptions extends Snack {
  _subscriptions?: SnackListenerSubscription[];
}

interface ExpoSnackViewerProps {
  files: Record<string, Database["public"]["Tables"]["prototype_files"]["Row"]>;
  onResetToDefault?: () => void;
  hideControls?: boolean;
  onCreateFile?: (fileName: string, initialContent?: string) => void;
  onDeleteFile?: (fileName: string) => void;
}

export interface ExpoSnackViewerRef {
  forceRefresh: () => void;
}

type PreviewMode = "web" | "mobile";

const ExpoSnackViewer = forwardRef<ExpoSnackViewerRef, ExpoSnackViewerProps>(
  (
    {
      files,
      onResetToDefault,
      hideControls = false,
      onCreateFile,
      onDeleteFile,
    },
    ref,
  ) => {
    const [snack, setSnack] = useState<SnackWithSubscriptions | null>(null);
    const [snackState, setSnackState] = useState<SnackState | null>(null);
    const [isLoading, setIsLoading] = useState(true);
    const [error, setError] = useState<string | null>(null);
    const [previewMode, setPreviewMode] = useState<PreviewMode>("mobile");
    const [refreshKey, setRefreshKey] = useState(0);
    const [mobileSize, setMobileSize] = useState({ width: 300, height: 600 });
    const [showNewFileModal, setShowNewFileModal] = useState(false);
    const [newFileName, setNewFileName] = useState("");
    const [newFileError, setNewFileError] = useState("");
    const [showDeleteConfirm, setShowDeleteConfirm] = useState(false);
    const [fileToDelete, setFileToDelete] = useState<string | null>(null);

    // Ref for the iframe's contentWindow
    const webPreviewRef = useRef<Window | null>(null);

    // Force refresh method
    const forceRefresh = useCallback(() => {
      if (snack && snackState?.webPreviewURL) {
        // Method 1: Try iframe refresh
        const iframe = document.querySelector(
          'iframe[title="React Native Preview"], iframe[title="React Native Web Preview"]',
        ) as HTMLIFrameElement;
        if (iframe) {
          const currentSrc = iframe.src;
          iframe.src = "about:blank";
          setTimeout(() => {
            iframe.src = currentSrc;
          }, 100);
        }

        // Method 2: Update refresh key to force React re-render
        setRefreshKey((prev) => prev + 1);
      }
    }, [snack, snackState?.webPreviewURL]);

    // Expose forceRefresh method to parent
    useImperativeHandle(
      ref,
      () => ({
        forceRefresh,
      }),
      [forceRefresh],
    );

    useEffect(() => {
      let snackSDK: SnackWithSubscriptions | null = null;

      const initializeSnack = () => {
        try {
          setIsLoading(true);
          setError(null);

          const initialFiles = Object.entries(files).reduce(
            (acc, [fileName, file]) => {
              acc[fileName] = {
                type: "CODE" as const,
                contents: file.contents,
              };
              return acc;
            },
            {} as Record<string, { type: "CODE"; contents: string }>,
          );

          snackSDK = new Snack({
            files: initialFiles,
            dependencies: DEFAULT_DEPENDENCIES,
            online: true,
            name: "React Native Chat Assistant",
            description: "Generated by AI assistant",
            webPreviewRef: webPreviewRef,
          });

          const stateSubscription = snackSDK.addStateListener((state) => {
            setSnackState(state);
          });

          const logSubscription = snackSDK.addLogListener((log) => {
            console.log("Snack log:", log);
          });

          setSnack(snackSDK);
          setSnackState(snackSDK.getState());
          setIsLoading(false);

          (snackSDK as SnackWithSubscriptions)._subscriptions = [
            stateSubscription,
            logSubscription,
          ];
        } catch (err) {
          console.error("Failed to initialize Snack:", err);
          setError(
            err instanceof Error ? err.message : "Failed to initialize Snack",
          );
          setIsLoading(false);
        }
      };

      initializeSnack();

      return () => {
        if (snackSDK && snackSDK._subscriptions) {
          snackSDK._subscriptions.forEach((unsubscribe) => {
            if (unsubscribe) {
              unsubscribe();
            }
          });
        }
      };
    }, [files]); // Include files dependency

    useEffect(() => {
      const updateSnackFiles = async () => {
        if (!snack) return;

        try {
          setError(null);
          const snackFiles = Object.entries(files).reduce(
            (acc, [fileName, file]) => {
              acc[fileName] = {
                type: "CODE" as const,
                contents: file.contents,
              };
              return acc;
            },
            {} as Record<string, { type: "CODE"; contents: string }>,
          );
          snack.updateFiles(snackFiles);
        } catch (err) {
          console.error("Failed to update Snack files:", err);
          setError(
            err instanceof Error ? err.message : "Failed to update code",
          );
        }
      };

      if (files) {
        updateSnackFiles();
      }
    }, [files, snack, forceRefresh]);

    const snackUrl = snackState?.url;
    const webPreviewURL = snackState?.webPreviewURL;

    const handleRefresh = () => {
      if (webPreviewRef.current && webPreviewURL) {
        webPreviewRef.current.location = webPreviewURL;
      }
    };

    const handleModeChange = (mode: PreviewMode) => {
      setPreviewMode(mode);
    };

    const handleMouseDown = (e: React.MouseEvent) => {
      e.preventDefault();
      e.stopPropagation();

      const startX = e.clientX;
      const startY = e.clientY;
      const startWidth = mobileSize.width;
      const startHeight = mobileSize.height;

      const handleMouseMove = (moveEvent: MouseEvent) => {
        const deltaX = moveEvent.clientX - startX;
        const deltaY = moveEvent.clientY - startY;

        const newWidth = Math.max(250, Math.min(500, startWidth + deltaX));
        const newHeight = Math.max(400, Math.min(800, startHeight + deltaY));

        setMobileSize({ width: newWidth, height: newHeight });
      };

      const handleMouseUp = () => {
        document.removeEventListener("mousemove", handleMouseMove);
        document.removeEventListener("mouseup", handleMouseUp);
        document.body.style.cursor = "";
        document.body.style.userSelect = "";
      };

      document.addEventListener("mousemove", handleMouseMove);
      document.addEventListener("mouseup", handleMouseUp);
      document.body.style.cursor = "se-resize";
      document.body.style.userSelect = "none";
    };

    const handleCreateFile = () => {
      if (!newFileName.trim()) {
        setNewFileError("File name is required");
        return;
      }

      // Check if file already exists
      if (files[newFileName.trim()]) {
        setNewFileError("File already exists");
        return;
      }

      // Validate file name (basic validation)
      const fileName = newFileName.trim();
      if (!/^[a-zA-Z0-9._/-]+$/.test(fileName)) {
        setNewFileError(
          "Invalid file name. Use only letters, numbers, dots, hyphens, underscores, and forward slashes.",
        );
        return;
      }

      // Get default content based on file extension
      const getDefaultContent = (name: string) => {
        const ext = name.split(".").pop()?.toLowerCase();
        switch (ext) {
          case "js":
          case "jsx":
            return `import React from 'react';\nimport { View, Text } from 'react-native';\n\nexport default function ${name.split(".")[0].replace(/[^a-zA-Z0-9]/g, "")}() {\n  return (\n    <View>\n      <Text>Hello from ${name}!</Text>\n    </View>\n  );\n}`;
          case "ts":
          case "tsx":
            return `import React from 'react';\nimport { View, Text } from 'react-native';\n\ninterface Props {}\n\nexport default function ${name.split(".")[0].replace(/[^a-zA-Z0-9]/g, "")}({}: Props) {\n  return (\n    <View>\n      <Text>Hello from ${name}!</Text>\n    </View>\n  );\n}`;
          case "json":
            return "{\n  \n}";
          case "md":
            return `# ${name.split(".")[0]}\n\nAdd your content here.`;
          case "css":
            return "/* Add your styles here */";
          default:
            return "";
        }
      };

      onCreateFile?.(fileName, getDefaultContent(fileName));
      setShowNewFileModal(false);
      setNewFileName("");
      setNewFileError("");
    };

    const handleModalClose = () => {
      setNewFileName("");
      setNewFileError("");
    };

    // const handleDeleteFile = (fileName: string) => {
    //   if (Object.keys(files).length <= 1) {
    //     return; // Prevent deleting the last file
    //   }
    //   setFileToDelete(fileName);
    //   setShowDeleteConfirm(true);
    // };

    const confirmDeleteFile = () => {
      if (fileToDelete && onDeleteFile) {
        onDeleteFile(fileToDelete);
        setShowDeleteConfirm(false);
        setFileToDelete(null);
      }
    };

    const cancelDeleteFile = () => {
      setShowDeleteConfirm(false);
      setFileToDelete(null);
    };

    return (
      <div className="flex flex-col h-full bg-background">
        {/* Header - only shows when not hidden and no file management controls */}
        {!hideControls && !onCreateFile && !onDeleteFile && (
          <div className="flex items-center justify-between p-6 bg-muted/30 border-b border-border">
            <div className="flex items-center gap-2">
              <svg
                className="w-4 h-4 text-muted-foreground"
                fill="none"
                stroke="currentColor"
                viewBox="0 0 24 24"
              >
                <path
                  strokeLinecap="round"
                  strokeLinejoin="round"
                  strokeWidth={2}
                  d="M9 12h6m-6 4h6m2 5H7a2 2 0 01-2-2V5a2 2 0 012-2h5.586a1 1 0 01.707.293l5.414 5.414a1 1 0 01.293.707V19a2 2 0 01-2 2z"
                />
              </svg>
              <span className="text-sm font-medium text-foreground">
                React Native Preview
              </span>
            </div>
          </div>
        )}

        {/* Status */}
        {(isLoading || error) && (
          <div className="p-4 bg-muted/50 border-b border-border">
            {isLoading && (
              <div className="flex items-center space-x-3">
                <Badge variant="secondary">
                  <div className="w-4 h-4 border-2 border-primary border-t-transparent rounded-full animate-spin mr-2"></div>
                  Loading preview...
                </Badge>
              </div>
            )}

            {error && (
              <div className="flex items-center space-x-3">
                <Badge variant="destructive">
                  <svg
                    className="w-4 h-4 mr-2"
                    fill="currentColor"
                    viewBox="0 0 20 20"
                  >
                    <path
                      fillRule="evenodd"
                      d="M18 10a8 8 0 11-16 0 8 8 0 0116 0zm-7 4a1 1 0 11-2 0 1 1 0 012 0zm-1-9a1 1 0 00-1 1v4a1 1 0 102 0V6a1 1 0 00-1-1z"
                      clipRule="evenodd"
                    />
                  </svg>
                  {error}
                </Badge>
              </div>
            )}
          </div>
        )}

        {/* Preview */}
        <div className="flex-1 relative flex items-center justify-center bg-background p-8">
          {/* Floating Options Button */}
          <div className="absolute top-4 right-4 z-10">
            <DropdownMenu>
              <DropdownMenuTrigger asChild>
                <Button
                  variant="secondary"
                  size="sm"
                  className="bg-background/90 backdrop-blur-sm shadow-lg border border-border"
                >
                  <Settings className="w-4 h-4" />
                </Button>
              </DropdownMenuTrigger>
              <DropdownMenuContent align="end" className="w-48">
                <DropdownMenuItem
                  onClick={() => handleModeChange("mobile")}
                  className={previewMode === "mobile" ? "bg-accent" : ""}
                >
                  <Smartphone className="w-4 h-4 mr-2" />
                  Mobile View
                </DropdownMenuItem>
                <DropdownMenuItem
                  onClick={() => handleModeChange("web")}
                  className={previewMode === "web" ? "bg-accent" : ""}
                >
                  <Monitor className="w-4 h-4 mr-2" />
                  Web View
                </DropdownMenuItem>
                <DropdownMenuSeparator />
                <DropdownMenuItem
                  onClick={handleRefresh}
                  disabled={isLoading || !webPreviewURL}
                >
                  <RefreshCw className="w-4 h-4 mr-2" />
                  Refresh Preview
                </DropdownMenuItem>
                {!hideControls && onResetToDefault && (
                  <DropdownMenuItem
                    onClick={onResetToDefault}
                    disabled={isLoading}
                    className="text-destructive focus:text-destructive"
                  >
                    <RotateCcw className="w-4 h-4 mr-2" />
                    Reset to Default
                  </DropdownMenuItem>
                )}
              </DropdownMenuContent>
            </DropdownMenu>
          </div>
          {isLoading && !webPreviewURL ? (
            <div className="flex items-center justify-center h-full">
              <div className="text-center bg-card p-8 rounded-lg border border-border">
                <div className="w-12 h-12 border-4 border-primary border-t-transparent rounded-full animate-spin mx-auto mb-6"></div>
                <p className="text-foreground text-lg font-medium">
                  Setting up your React Native preview...
                </p>
              </div>
            </div>
          ) : previewMode === "mobile" ? (
            /* --- START: iPhone 15 Pro device frame --- */
            <div
              id="mobile-frame"
              className="relative mx-auto select-none"
              style={{
                width: mobileSize.width + 16,
                height: mobileSize.height + 16,
              }}
            >
              {/* iPhone 15 Pro frame with titanium-like appearance */}
              <div
                className="relative bg-gradient-to-br from-gray-700 via-gray-800 to-gray-900 shadow-2xl"
                style={{
                  width: mobileSize.width + 16,
                  height: mobileSize.height + 16,
                  borderRadius: "2.5rem",
                  border: "1px solid #1f2937",
                  boxShadow:
                    "0 25px 50px -12px rgba(0, 0, 0, 0.5), inset 0 1px 0 rgba(255, 255, 255, 0.1)",
                }}
              >
                {/* Dynamic Island */}
                <div
                  className="absolute bg-black rounded-full"
                  style={{
                    width: mobileSize.width * 0.4,
                    height: "24px",
                    top: "6px",
                    left: "50%",
                    transform: "translateX(-50%)",
                    borderRadius: "12px",
                  }}
                ></div>

                {/* Volume buttons */}
                <div className="absolute -left-[3px] top-[80px] w-[2px] h-[32px] bg-gray-600 rounded-l-lg"></div>
                <div className="absolute -left-[3px] top-[120px] w-[2px] h-[32px] bg-gray-600 rounded-l-lg"></div>
                <div className="absolute -left-[3px] top-[160px] w-[2px] h-[48px] bg-gray-600 rounded-l-lg"></div>

                {/* Power button */}
                <div className="absolute -right-[3px] top-[140px] w-[2px] h-[48px] bg-gray-600 rounded-r-lg"></div>

                {/* Screen area */}
                <div
                  className="absolute bg-black overflow-hidden"
                  style={{
                    width: mobileSize.width,
                    height: mobileSize.height,
                    top: "8px",
                    left: "8px",
                    borderRadius: "2.2rem",
                    boxShadow: "inset 0 0 0 1px rgba(255, 255, 255, 0.1)",
                  }}
                >
                  <iframe
                    key={`mobile-${refreshKey}`}
                    ref={(c) => {
                      webPreviewRef.current = c?.contentWindow ?? null;
                    }}
                    className="w-full h-full"
                    title="React Native Preview"
                    src={webPreviewURL}
                    sandbox="allow-scripts allow-same-origin allow-forms allow-downloads allow-modals allow-popups allow-presentation"
                  />
                </div>

                {/* Resize handle */}
                <div
                  className="absolute bottom-1 right-1 w-4 h-4 cursor-se-resize opacity-60 hover:opacity-100 transition-opacity"
                  onMouseDown={handleMouseDown}
                >
                  <div className="w-full h-full bg-gray-400 rounded-sm flex items-center justify-center">
                    <svg
                      width="8"
                      height="8"
                      viewBox="0 0 8 8"
                      fill="currentColor"
                    >
                      <path d="M8 0v2L6 0h2zM8 4v2L6 4h2zM8 8v0L6 6h2zM4 8v0L2 6h2z" />
                    </svg>
                  </div>
                </div>
              </div>
            </div>
          ) : (
            /* --- END: Mobile device frame --- */
            /* --- START: Web preview --- */
            <div className="w-full h-full max-w-6xl mx-auto">
              <div className="bg-card rounded-lg border border-border overflow-hidden h-full">
                <div className="bg-muted px-6 py-4 border-b border-border flex items-center space-x-3">
                  <div className="flex space-x-2">
                    <div className="w-3 h-3 bg-destructive rounded-full"></div>
                    <div className="w-3 h-3 bg-amber-500 rounded-full"></div>
                    <div className="w-3 h-3 bg-green-500 rounded-full"></div>
                  </div>
                  <span className="text-sm text-foreground font-medium ml-3">
                    Web Preview
                  </span>
                </div>
                <iframe
                  key={`web-${refreshKey}`}
                  ref={(c) => {
                    webPreviewRef.current = c?.contentWindow ?? null;
                  }}
                  className="w-full h-full min-h-[500px]"
                  title="React Native Web Preview"
                  src={webPreviewURL}
                  sandbox="allow-scripts allow-same-origin allow-forms allow-downloads allow-modals allow-popups allow-presentation"
                />
              </div>
            </div>
            /* --- END: Web preview --- */
          )}
        </div>

        {/* File Info */}
        {false && (
          <div className="border-t border-border p-6 bg-muted/30">
            <div className="flex items-center gap-3 flex-wrap">
              <div className="flex items-center gap-2">
                <svg
                  className="w-4 h-4 text-muted-foreground"
                  fill="none"
                  stroke="currentColor"
                  viewBox="0 0 24 24"
                >
                  <path
                    strokeLinecap="round"
                    strokeLinejoin="round"
                    strokeWidth={2}
                    d="M9 12h6m-6 4h6m2 5H7a2 2 0 01-2-2V5a2 2 0 012-2h5.586a1 1 0 01.707.293l5.414 5.414a1 1 0 01.293.707V19a2 2 0 01-2 2z"
                  />
                </svg>
                <span className="text-sm font-medium text-foreground">
                  Included Files ({Object.keys(files).length})
                </span>
              </div>
              <div className="flex gap-2 flex-wrap">
                {Object.keys(files).map((fileName) => (
                  <Badge
                    key={fileName}
                    variant="secondary"
                    className="text-xs font-mono"
                  >
                    {fileName}
                  </Badge>
                ))}
                {snackUrl && (
                  <Badge variant="default" className="text-xs">
                    <div className="w-2 h-2 bg-green-400 rounded-full animate-pulse mr-2"></div>
                    Live Preview
                  </Badge>
                )}
              </div>
            </div>
          </div>
        )}

        {/* New File Modal */}
        <Dialog
          open={showNewFileModal}
          onOpenChange={(open) => {
            setShowNewFileModal(open);
            if (!open) {
              handleModalClose();
            }
          }}
        >
          <DialogContent className="sm:max-w-md">
            <DialogHeader>
              <DialogTitle>Create New File</DialogTitle>
            </DialogHeader>

            <div className="space-y-4">
              <div>
                <Label htmlFor="fileName" className="text-sm font-medium">
                  File Name
                </Label>
                <Input
                  id="fileName"
                  type="text"
                  value={newFileName}
                  onChange={(e) => {
                    setNewFileName(e.target.value);
                    setNewFileError("");
                  }}
                  placeholder="e.g., components/MyComponent.tsx"
                  className="mt-2"
                  autoFocus
                />
                {newFileError && (
                  <p className="text-destructive text-sm mt-1">
                    {newFileError}
                  </p>
                )}
              </div>

              <div className="text-sm text-muted-foreground">
                <p className="mb-2">Supported file types:</p>
                <ul className="list-disc list-inside space-y-1 text-xs">
                  <li>.js, .jsx - JavaScript/React components</li>
                  <li>.ts, .tsx - TypeScript/React components</li>
                  <li>.json - JSON configuration files</li>
                  <li>.md - Markdown documentation</li>
                  <li>.css - Stylesheets</li>
                </ul>
              </div>
            </div>

            <DialogFooter>
              <Button
                variant="ghost"
                onClick={() => setShowNewFileModal(false)}
              >
                Cancel
              </Button>
              <Button onClick={handleCreateFile}>Create File</Button>
            </DialogFooter>
          </DialogContent>
        </Dialog>

        {/* Delete Confirmation Modal */}
        <Dialog open={showDeleteConfirm} onOpenChange={setShowDeleteConfirm}>
          <DialogContent className="sm:max-w-md">
            <DialogHeader>
              <DialogTitle>Delete File</DialogTitle>
            </DialogHeader>

            <div className="space-y-4">
              <p className="text-sm text-muted-foreground">
                Are you sure you want to delete{" "}
                <span className="font-mono font-medium text-foreground">
                  {fileToDelete}
                </span>
                ? This action cannot be undone.
              </p>
            </div>

            <DialogFooter>
              <Button variant="ghost" onClick={cancelDeleteFile}>
                Cancel
              </Button>
              <Button variant="destructive" onClick={confirmDeleteFile}>
                Delete File
              </Button>
            </DialogFooter>
          </DialogContent>
        </Dialog>
      </div>
    );
  },
);

ExpoSnackViewer.displayName = "ExpoSnackViewer";

export default ExpoSnackViewer;
