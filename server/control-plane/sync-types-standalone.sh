#!/bin/bash

# Standalone Type Sync Script
# This script can be run independently without npm

set -e  # Exit on any error

echo "🔄 Syncing API types (standalone)..."

SOURCE_FILE="./types/PublicAPITypes.ts"
TARGET_FILE="../../web-application/src/lib/types/serverAPITypes.ts"

# Check if source file exists
if [ ! -f "$SOURCE_FILE" ]; then
    echo "❌ Source file not found: $SOURCE_FILE"
    exit 1
fi

# Create target directory if it doesn't exist
TARGET_DIR=$(dirname "$TARGET_FILE")
if [ ! -d "$TARGET_DIR" ]; then
    echo "📁 Creating target directory: $TARGET_DIR"
    mkdir -p "$TARGET_DIR"
fi

# Create header
HEADER="// THIS FILE IS AUTO-GENERATED
// Do not edit this file directly. It is synchronized from:
// @server/control-plane/types/PublicAPITypes.ts
// 
// To update these types, modify the source file and run:
// npm run build (in the control-plane directory)
//
// Last synced: $(date -u +"%Y-%m-%dT%H:%M:%S.%3NZ")

"

# Sync the file
echo "$HEADER" > "$TARGET_FILE"
cat "$SOURCE_FILE" >> "$TARGET_FILE"

echo "✅ Successfully synced types to: $TARGET_FILE"
echo "📊 File size: $(du -h "$TARGET_FILE" | cut -f1)"
echo "📝 Lines synced: $(wc -l < "$SOURCE_FILE")"