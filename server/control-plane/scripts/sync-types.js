#!/usr/bin/env node

/**
 * Type Sync Script
 *
 * Syncs type files across the monorepo:
 * 1. PublicAPITypes.ts: control-plane -> web-application
 * 2. ChatTypes.ts: build-workers -> web-application
 * 3. PublicAPITypes.ts: control-plane -> build-workers (as ControlPlaneTypes.ts)
 *
 * This ensures all services have consistent type definitions
 */

import fs from 'fs/promises';
import path from 'path';
import { fileURLToPath } from 'url';

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);

// Define sync configurations
const SYNC_CONFIGS = [
  {
    name: 'PublicAPITypes (control-plane → web-application)',
    source: path.resolve(__dirname, '../types/PublicAPITypes.ts'),
    target: path.resolve(
      __dirname,
      '../../../web-application/src/lib/types/serverAPITypes.ts',
    ),
    sourceLocation: '@server/control-plane/types/PublicAPITypes.ts',
  },
  {
    name: 'ChatTypes (build-workers → web-application)',
    source: path.resolve(__dirname, '../../build-workers/types/ChatTypes.ts'),
    target: path.resolve(
      __dirname,
      '../../../web-application/src/lib/types/ChatTypes.ts',
    ),
    sourceLocation: '@server/build-workers/types/ChatTypes.ts',
  },
  {
    name: 'PublicAPITypes (control-plane → build-workers)',
    source: path.resolve(__dirname, '../types/PublicAPITypes.ts'),
    target: path.resolve(
      __dirname,
      '../../build-workers/types/ControlPlaneTypes.ts',
    ),
    sourceLocation: '@server/control-plane/types/PublicAPITypes.ts',
  },
];

async function syncSingleFile(config) {
  const { name, source, target, sourceLocation } = config;

  console.log(`\n🔄 Syncing ${name}...`);

  // Check if source file exists
  try {
    await fs.access(source);
  } catch {
    console.error(`❌ Source file not found: ${source}`);
    return false;
  }

  // Read the source file
  const sourceContent = await fs.readFile(source, 'utf-8');

  // Create target directory if it doesn't exist
  const targetDir = path.dirname(target);
  try {
    await fs.access(targetDir);
  } catch {
    console.log(`📁 Creating target directory: ${targetDir}`);
    await fs.mkdir(targetDir, { recursive: true });
  }

  // Create the header comment for the target file
  const header = `// THIS FILE IS AUTO-GENERATED
// Do not edit this file directly. It is synchronized from:
// ${sourceLocation}
//
// To update these types, modify the source file and run:
// npm run build (in the control-plane directory)
//
// Last synced: ${new Date().toISOString()}

`;

  // Write the synced file with header
  await fs.writeFile(target, header + sourceContent, 'utf-8');

  console.log(`✅ Successfully synced to: ${target}`);
  console.log(`📊 File size: ${(sourceContent.length / 1024).toFixed(2)} KB`);

  // Get line count for reporting
  const lineCount = sourceContent.split('\n').length;
  console.log(`📝 Lines synced: ${lineCount}`);

  return true;
}

async function syncTypes() {
  try {
    console.log('🚀 Starting type synchronization across monorepo...\n');

    let allSuccessful = true;

    for (const config of SYNC_CONFIGS) {
      const success = await syncSingleFile(config);
      if (!success) {
        allSuccessful = false;
      }
    }

    if (allSuccessful) {
      console.log('\n✨ All type files synced successfully!');
    } else {
      console.error('\n⚠️  Some type files failed to sync');
      process.exit(1);
    }
  } catch (error) {
    console.error('❌ Error syncing types:', error.message);
    process.exit(1);
  }
}

// Run the sync
syncTypes();
