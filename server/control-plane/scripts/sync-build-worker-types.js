#!/usr/bin/env node

/**
 * Build Worker Type Sync Script
 *
 * Syncs build-worker-api-types.ts from build-workers to control-plane
 * This ensures the control plane always has the latest build worker type definitions
 */

import fs from 'fs/promises';
import path from 'path';
import { fileURLToPath } from 'url';

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);

// File paths
const SOURCE_FILE = path.resolve(
  __dirname,
  '../../build-workers/types/BuildWorkerTypes.ts',
);

const TARGET_FILES = [
  {
    path: path.resolve(__dirname, '../types/BuildWorkerTypes.ts'),
    name: 'control-plane',
  },
  {
    path: path.resolve(
      __dirname,
      '../../../web-application/src/lib/types/SandboxAPITypes.ts',
    ),
    name: 'web-application',
  },
];

async function syncBuildWorkerTypes() {
  try {
    console.log(
      '🔄 Syncing build worker types from build-workers to multiple targets...',
    );

    // Check if source file exists
    try {
      await fs.access(SOURCE_FILE);
    } catch {
      console.error(`❌ Source file not found: ${SOURCE_FILE}`);
      process.exit(1);
    }

    // Read the source file
    const sourceContent = await fs.readFile(SOURCE_FILE, 'utf-8');

    // Get line count for reporting
    const lineCount = sourceContent.split('\n').length;
    console.log(`📊 Source file size: ${(sourceContent.length / 1024).toFixed(2)} KB`);
    console.log(`📝 Lines to sync: ${lineCount}`);
    console.log('');

    // Sync to all target files
    for (const target of TARGET_FILES) {
      console.log(`🎯 Syncing to ${target.name}...`);

      // Create target directory if it doesn't exist
      const targetDir = path.dirname(target.path);
      try {
        await fs.access(targetDir);
      } catch {
        console.log(`📁 Creating target directory: ${targetDir}`);
        await fs.mkdir(targetDir, { recursive: true });
      }

      // Create the header comment for the target file
      const header = `// THIS FILE IS AUTO-GENERATED
// Do not edit this file directly. It is synchronized from:
// @server/build-workers/types/BuildWorkerTypes.ts
//
// To update these types, modify the source file and run:
// npm run sync-build-worker-types
//
// Last synced: ${new Date().toISOString()}

`;

      // Write the synced file with header
      await fs.writeFile(target.path, header + sourceContent, 'utf-8');

      console.log(`✅ Successfully synced to: ${target.path}`);
      console.log('');
    }

    console.log(`🎉 All targets synced successfully!`);
  } catch (error) {
    console.error('❌ Error syncing build worker types:', error.message);
    process.exit(1);
  }
}

// Run the sync
syncBuildWorkerTypes();
