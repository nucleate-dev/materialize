import fs from "fs/promises";
import path from "path";
import { SystemLogger } from "../../../loggers/SystemLogger.js";
import { SupabaseClientService } from "../../SupabaseClientService.js";
import type { Database } from "../../../types/supabase.js";

type PrototypeEnvVarRow =
  Database["public"]["Tables"]["prototype_env_vars"]["Row"];
type PrototypeEnvVarSecretRow =
  Database["public"]["Tables"]["prototype_env_var_secrets"]["Row"];

type PrototypeEnvVarWithSecret = PrototypeEnvVarRow & {
  prototype_env_var_secrets?: Pick<
    PrototypeEnvVarSecretRow,
    "secret_value"
  > | null;
};

type EnvVarRecord = PrototypeEnvVarWithSecret & {
  name: string;
  secret_value: string | null;
};

export async function syncPrototypeEnvVarsToDisk(options: {
  prototypeId: string;
  workDir: string;
  supabaseClientService: SupabaseClientService;
  logger: SystemLogger;
}): Promise<{ success: boolean; envVarCount: number; error?: string }> {
  const { prototypeId, workDir, supabaseClientService, logger } = options;

  if (!prototypeId) {
    return {
      success: false,
      envVarCount: 0,
      error: "Prototype ID is required to sync environment variables",
    };
  }

  try {
    const supabaseClient = supabaseClientService.getClient();
    const { data, error } = await supabaseClient
      .from("prototype_env_vars")
      .select("name, prototype_env_var_secrets(secret_value)")
      .eq("prototype_id", prototypeId)
      .order("name", { ascending: true });

    if (error) {
      logger.error(
        error,
        "Failed to fetch prototype environment variables from Supabase",
        { prototypeId },
      );
      return {
        success: false,
        envVarCount: 0,
        error: error.message,
      };
    }

    type WritableEnvVar = EnvVarRecord & { secret_value: string };

    const envVarRows = (data ?? []) as PrototypeEnvVarWithSecret[];
    const envVarRecords: EnvVarRecord[] = envVarRows.map((row) => ({
      ...row,
      name: row.name ?? "",
      secret_value: row.prototype_env_var_secrets?.secret_value ?? null,
    }));

    const namedEnvVars = envVarRecords.filter((row) => Boolean(row.name));

    const writableEnvVars = namedEnvVars.filter(
      (row): row is WritableEnvVar => {
        const trimmedValue = row.secret_value?.trim();
        if (!trimmedValue) {
          logger.warn(
            "Skipping environment variable without a secret value while syncing to disk",
            {
              prototypeId,
              envVarName: row.name,
            },
          );
          return false;
        }
        return true;
      },
    );

    const envFileLines = writableEnvVars.map(
      (row) =>
        `${normalizeEnvVarName(row.name)}=${escapeEnvValue(row.secret_value)}`,
    );
    const envFileContents = [
      "# Autogenerated by Materialize dev server",
      ...envFileLines,
      "",
    ].join("\n");

    const envPath = path.join(workDir, ".env");
    await fs.writeFile(envPath, envFileContents, "utf8");

    logger.consoleLogDevOnly("info", "Wrote prototype env vars to disk", {
      prototypeId,
      envVarCount: writableEnvVars.length,
      envFilePath: envPath,
    });

    return {
      success: true,
      envVarCount: writableEnvVars.length,
    };
  } catch (error) {
    const message = error instanceof Error ? error.message : String(error);
    logger.error(
      error instanceof Error ? error : new Error(message),
      "Failed to sync prototype env vars to disk",
      { prototypeId },
    );
    return {
      success: false,
      envVarCount: 0,
      error: message,
    };
  }
}

function normalizeEnvVarName(name: string): string {
  return name
    .trim()
    .replace(/[^A-Z0-9_]/gi, "_")
    .toUpperCase();
}

function escapeEnvValue(value: string): string {
  if (value === "") {
    return '""';
  }

  const needsQuoting = /[\s#"'\\]/.test(value) || value.includes("$");
  if (!needsQuoting) {
    return value;
  }

  const escaped = value.replace(/\\/g, "\\\\").replace(/"/g, '\\"');
  return `"${escaped}"`;
}
